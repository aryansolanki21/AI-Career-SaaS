import type { Analysis } from "./types";

type Rgb = [number, number, number];
type Priority = Analysis["suggestions"][number]["priority"];

const INK: Rgb = [15, 23, 42];
const MUTED: Rgb = [100, 116, 139];
const RULE: Rgb = [226, 232, 240];
const TRACK: Rgb = [241, 245, 249];

const PRIORITY_ORDER: Record<Priority, number> = { high: 0, medium: 1, low: 2 };
const PRIORITY_LABEL: Record<Priority, string> = {
  high: "High priority",
  medium: "Medium priority",
  low: "Low priority",
};

const scoreColor = (score: number): Rgb => {
  if (score >= 80) return [4, 120, 87];
  if (score >= 60) return [180, 83, 9];
  return [185, 28, 28];
};

const clean = (text: string): string =>
  text
    .replace(/[\u2192\u21D2]/g, "->")
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, "-")
    .replace(/\u2022/g, "-")
    .replace(/[\s\S]/g, (char) => {
      const code = char.charCodeAt(0);
      return code === 9 ||
        code === 10 ||
        code === 13 ||
        (code >= 32 && code <= 126) ||
        (code >= 160 && code <= 255)
        ? char
        : "";
    });

export async function downloadReport(result: Analysis): Promise<void> {
  // Loaded on demand so jsPDF is not part of the main bundle.
  const { default: jsPDF } = await import("jspdf");

  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const marginX = 18;
  const contentWidth = 210 - marginX * 2;
  const pageBottom = 280;
  let y = 22;

  const ensureSpace = (needed: number) => {
    if (y + needed > pageBottom) {
      doc.addPage();
      y = 20;
    }
  };

  const write = (
    text: string,
    size: number,
    style: "normal" | "bold",
    color: Rgb,
    width = contentWidth,
  ) => {
    doc
      .setFont("helvetica", style)
      .setFontSize(size)
      .setTextColor(...color);
    const lineHeight = size * 0.5;
    const lines = doc.splitTextToSize(clean(text), width) as string[];

    for (const line of lines) {
      ensureSpace(lineHeight);
      doc.text(line, marginX, y);
      y += lineHeight;
    }
  };

  const heading = (text: string) => {
    ensureSpace(18);
    y += 4;
    write(text, 12, "bold", INK);
    y += 1;
    doc
      .setDrawColor(...RULE)
      .setLineWidth(0.3)
      .line(marginX, y, marginX + contentWidth, y);
    y += 6;
  };

  /* Title */
  write("ATS compatibility report", 18, "bold", INK);
  y += 1;
  write(
    `Generated by CareerCraft AI on ${new Date().toLocaleDateString("en-IN", {
      day: "numeric",
      month: "long",
      year: "numeric",
    })}`,
    9,
    "normal",
    MUTED,
  );
  y += 8;

  /* Overall score */
  const overall = Math.round(result.atsScore);
  doc
    .setFont("helvetica", "bold")
    .setFontSize(34)
    .setTextColor(...scoreColor(overall));
  const overallWidth = doc.getTextWidth(String(overall));
  doc.text(String(overall), marginX, y + 8);
  doc
    .setFont("helvetica", "normal")
    .setFontSize(10)
    .setTextColor(...MUTED);
  doc.text("out of 100", marginX + overallWidth + 3, y + 8);
  y += 16;
  write(result.summary, 10, "normal", INK);

  /* Breakdown */
  heading("Score breakdown");
  for (const [key, block] of Object.entries(result.scoreBreakdown)) {
    ensureSpace(22);

    const label = key.charAt(0).toUpperCase() + key.slice(1);
    const score = Math.round(block.score);

    doc
      .setFont("helvetica", "bold")
      .setFontSize(10)
      .setTextColor(...INK);
    doc.text(label, marginX, y);

    const scoreText = `${score}/100`;
    doc.setTextColor(...scoreColor(score));
    doc.text(
      scoreText,
      marginX + contentWidth - doc.getTextWidth(scoreText),
      y,
    );
    y += 3;

    doc.setFillColor(...TRACK).rect(marginX, y, contentWidth, 2, "F");
    doc
      .setFillColor(...scoreColor(score))
      .rect(
        marginX,
        y,
        (contentWidth * Math.min(100, Math.max(0, score))) / 100,
        2,
        "F",
      );
    y += 6;

    write(block.feedback, 9, "normal", MUTED);
    y += 4;
  }

  /* Strengths */
  heading("What is working");
  if (result.strengths.length === 0) {
    write("No strengths were returned for this analysis.", 10, "normal", MUTED);
  }
  for (const strength of result.strengths) {
    write(`- ${strength}`, 10, "normal", INK);
    y += 1.5;
  }

  /* Suggestions, most important first */
  heading("What to fix");
  const suggestions = [...result.suggestions].sort(
    (a, b) => PRIORITY_ORDER[a.priority] - PRIORITY_ORDER[b.priority],
  );

  if (suggestions.length === 0) {
    write("No improvement suggestions were returned.", 10, "normal", MUTED);
  }

  suggestions.forEach((item, index) => {
    ensureSpace(30);

    doc
      .setFont("helvetica", "bold")
      .setFontSize(11)
      .setTextColor(...INK);
    doc.text(clean(item.category), marginX, y);

    const badge = PRIORITY_LABEL[item.priority];
    doc
      .setFont("helvetica", "normal")
      .setFontSize(9)
      .setTextColor(...MUTED);
    doc.text(badge, marginX + contentWidth - doc.getTextWidth(badge), y);
    y += 6;

    write("Issue", 9, "bold", MUTED);
    write(item.issue, 10, "normal", INK);
    y += 2;
    write("Recommendation", 9, "bold", MUTED);
    write(item.recommendation, 10, "normal", INK);
    y += 4;

    if (index < suggestions.length - 1) {
      ensureSpace(6);
      doc
        .setDrawColor(...RULE)
        .setLineWidth(0.2)
        .line(marginX, y, marginX + contentWidth, y);
      y += 6;
    }
  });

  /* Footnote */
  y += 6;
  write(
    "This score estimates how well your resume matches ATS and recruiter expectations. It does not guarantee that your application will be accepted.",
    8,
    "normal",
    MUTED,
  );

  doc.save("resume-analysis-report.pdf");
}
